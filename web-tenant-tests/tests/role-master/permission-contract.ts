/**
 * Hợp đồng quyền của MỌI endpoint GHI (POST/PUT/PATCH/DELETE) của API tenant.
 *
 * Mỗi dòng: "<METHOD> <route OpenAPI>" → quyền BE đòi:
 *   · ['<screen>.edit', …] — RequirePermission (AnyOf: có 1 mã là qua). Admin luôn qua.
 *   · ADMIN               — policy TenantAdmin (chỉ role 管理者).
 *   · OPEN.<lý do>        — cố ý KHÔNG gắn quyền; spec KHÔNG gọi các endpoint này.
 *
 * Bảng được trích từ Endpoints/Tenant/*.cs (demo1 2026-10-20) rồi soát tay.
 * role-permission-api.spec.ts đối chiếu bảng với /openapi/tenant.json: endpoint ghi mới
 * chưa có dòng ở đây ⇒ spec đỏ cho tới khi được phân loại. Đừng thêm dòng cho xanh
 * mà không đọc endpoint đó.
 */
