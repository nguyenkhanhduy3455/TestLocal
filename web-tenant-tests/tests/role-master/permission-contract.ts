    /** Đăng ký máy / đồng bộ cấu hình agent (hạ tầng, không phải dữ liệu màn hình). */
    DEVICE: 'open:device',
    /** Dựng lại index pic_list từ thư mục ảnh khi mở màn — CÓ ghi DB (xoá + chèn index). */
